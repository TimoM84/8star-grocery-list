const INDEX: { key: string; category: string }[] = RULES.flatMap(([category, words]) =>
	words.map((w) => ({ key: searchKey(w), category }))
).sort((a, b) => b.key.length - a.key.length);

/** Returns a category id from the default set, or null when nothing matches. */
export function guessCategory(name: string): string | null {
	const key = searchKey(name);
	if (!key) return null;
	const words = key.split(/[\s-]+/);
	// 1. Exact name or exact word match (longest keyword first).
	for (const entry of INDEX) {
		if (
			key === entry.key ||
			(entry.key.includes(' ') ? key.includes(entry.key) : words.includes(entry.key))
		)
			return entry.category;
	}
	// 2. Compound words: Dutch glues words together ("volkorenbrood", "kippensoep").
	//    The last part usually determines the category.
	for (const entry of INDEX) {
		if (entry.key.length >= 4 && key.endsWith(entry.key)) return entry.category;
	}
	return null;
}
